"""build-catalog.py: turn the VIBE spreadsheet into catalog.js.

    python3 build-catalog.py

Reads ../cgf14556-sup-0001-s2.xlsx (the supplementary table of the VIBE design
space) and writes ../assets/catalog.js: one record per example, with the
spreadsheet's codes and the screenshot that shows it. Screenshot "Row N" is the
(N - 5)th example in the sheet. Row 30 has a screenshot but no sheet row, so it
is added by hand below.
"""
import json, os, re
import openpyxl

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
SHOTS = 'Screenshots of Belief-Driven Elicitation Examples 2'

def clean(v):
    if v is None: return None
    s = re.sub(r'\s+', ' ', str(v)).strip().strip(',').strip()
    if s.endswith('.0') and s[:-2].isdigit(): s = s[:-2]
    return s or None

ws = openpyxl.load_workbook(os.path.join(root, 'cgf14556-sup-0001-s2.xlsx')).active
rows = [r for r in ws.iter_rows(min_row=4, values_only=True) if r[0]]
out = []
for k, r in enumerate(rows):
    n = k + 6
    src = clean(r[1])
    src = {'538': 'FiveThirtyEight', 'NYT': 'The New York Times', 'Guardian': 'The Guardian', 'CNN': 'CNN'}.get(src, src)
    out.append({
        'id': f'row-{n:02d}', 'row': n,
        'title': clean(r[0]), 'source': src, 'url': clean(r[2]).replace(' ', '') if r[2] else None,
        'screenshot': f'{SHOTS}/Row {n}.png',
        'codes': {
            'why': clean(r[3]),
            'who': clean(r[4]),
            'expertise': {'graphical': clean(r[5]), 'statistical': clean(r[6]), 'domain': clean(r[7])},
            'parameter': clean(r[8]) or clean(r[9]) or clean(r[10]),
            'uncertainty': clean(r[11]),
            'inference': clean(r[12]),
            'interaction': clean(r[13]),
            'vis': clean(r[14]),
            'uncertaintyMethod': clean(r[15]),
            'feedbackType': clean(r[16]),
            'feedbackSource': clean(r[17]),
        },
    })
out.append({
    'id': 'row-30', 'row': 30,
    'title': 'Thinking in distributions (unidentified tutorial)', 'source': 'Unknown', 'url': None,
    'screenshot': f'{SHOTS}/Row 30.png',
    'codes': None,
    'note': 'Not in the spreadsheet: only the screenshot is in the folder. A story-driven tutorial (a "Monk" guides a hero) that teaches probability distributions, then asks for a min and max guess.',
})
with open(os.path.join(root, 'assets', 'catalog.js'), 'w') as f:
    f.write('// Generated by tools/build-catalog.py from the VIBE spreadsheet. Do not edit.\n')
    f.write('window.CATALOG = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
print(len(out), 'examples')
